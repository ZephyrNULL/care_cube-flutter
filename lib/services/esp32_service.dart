const char* WIFI_PASSWORD = "YOUR_WIFI_PASSWORD";
const char* BOX_ID        = "$boxId";
const char* MQTT_SERVER    = "broker.hivemq.com";
const int   MQTT_PORT      = 1883;

#define SDA_PIN 21
#define SCL_PIN 22
#define DHTPIN 4
#define DHTTYPE DHT22
#define BUZZER 25
#define LED1 26
#define LED2 27
#define XSHUT1 18
#define XSHUT2 19

