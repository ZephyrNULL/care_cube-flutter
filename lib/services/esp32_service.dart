LiquidCrystal_I2C lcd(0x27, 16, 4);
DHT dht(DHTPIN, DHTTYPE);
VL53L0X sensor1;
VL53L0X sensor2;

WiFiClient   wifiClient;
PubSubClient  mqtt(wifiClient);
